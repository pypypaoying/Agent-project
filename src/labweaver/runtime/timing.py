"""Host-clock task timing, independent of model text and replayed messages."""

import math
import threading
import time


class TaskTiming:
    """Count active segments and genuine model calls without charging human wait."""

    def __init__(self, *, clock=time.monotonic, source="agent_monotonic"):
        self.clock, self.source = clock, source
        self._lock = threading.RLock()
        self.reset()

    def reset(self):
        with self._lock:
            self.origin = self.started = self.clock()
            self.elapsed = 0.0
            self.finished = None
            self.models, self.completed_models = {}, {}

    def pause(self):
        with self._lock:
            if self.started is not None:
                self.elapsed += max(0.0, self.clock() - self.started)
                self.started = None
            self.finish_models()

    def finish_models(self):
        """Freeze an unfinished request at verified worker termination, not cleanup."""
        with self._lock:
            current = self.clock()
            for key, started in self.models.items():
                self.completed_models.setdefault(key, max(0.0, current - started))
            self.models.clear()

    def resume(self):
        with self._lock:
            if self.started is None and self.finished is None:
                self.started = self.clock()

    def stop(self):
        with self._lock:
            if self.finished is None:
                self.pause()
                self.finished = self.clock()

    def observe(self, kind, payload):
        if kind not in {"model_start", "model_end"}:
            return
        key = (payload.get("role"), payload.get("parent_call_id"), payload.get("call"))
        if key[0] not in {"main", "analysis"} or isinstance(key[2], bool) or not isinstance(key[2], int) or key[2] < 1:
            return
        with self._lock:
            if kind == "model_start" and self.started is not None and key not in self.completed_models:
                current = self.clock()
                marked = payload.get("started_monotonic")
                # This marker is generated by the harness, never the model.
                # Python's monotonic clock is shared by processes on supported OSes.
                started = marked if isinstance(marked, (int, float)) and not isinstance(marked, bool) and math.isfinite(marked) and self.origin <= marked <= current else current
                self.models.setdefault(key, started)
            elif kind == "model_end" and key not in self.completed_models:
                started = self.models.pop(key, None)
                duration = payload.get("elapsed_seconds")
                if isinstance(duration, (int, float)) and not isinstance(duration, bool) and math.isfinite(duration) and duration >= 0:
                    self.completed_models[key] = float(duration)
                elif started is not None:
                    self.completed_models[key] = max(0.0, self.clock() - started)

    def snapshot(self):
        with self._lock:
            current = self.finished if self.finished is not None else self.clock()
            running = self.started is not None
            models = [
                {"role": role, "parent_call_id": parent, "call": call,
                 "elapsed_seconds": round(max(0.0, current - started), 3)}
                for (role, parent, call), started in self.models.items()
            ]
            return {
                "version": 1, "source": self.source, "active": running,
                "active_seconds": round(self.elapsed + (max(0.0, current - self.started) if running else 0.0), 3),
                "wall_seconds": round(max(0.0, current - self.origin), 3),
                "model_seconds": round(sum(self.completed_models.values()) + sum(m["elapsed_seconds"] for m in models), 3),
                "model_calls": len(self.completed_models) + len(self.models),
                "current_models": models,
            }
